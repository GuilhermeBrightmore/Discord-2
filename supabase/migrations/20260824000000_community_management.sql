create table if not exists public.server_roles (
  id uuid primary key default gen_random_uuid(),
  server_id uuid not null references public.servers(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 64),
  color text not null default '#8b5cf6' check (color ~ '^#[0-9a-fA-F]{6}$'),
  position integer not null default 1 check (position >= 0),
  permissions jsonb not null default '{}'::jsonb,
  is_everyone boolean not null default false,
  created_at timestamptz not null default now(),
  unique (id, server_id),
  unique (server_id, name)
);
create unique index if not exists server_roles_everyone_idx on public.server_roles(server_id) where is_everyone;
create index if not exists server_roles_server_position_idx on public.server_roles(server_id, position desc);

create table if not exists public.member_roles (
  server_id uuid not null,
  user_id uuid not null,
  role_id uuid not null,
  assigned_by uuid references public.profiles(id) on delete set null,
  assigned_at timestamptz not null default now(),
  primary key (server_id, user_id, role_id),
  foreign key (server_id, user_id) references public.server_members(server_id, user_id) on delete cascade,
  foreign key (role_id, server_id) references public.server_roles(id, server_id) on delete cascade
);

create table if not exists public.server_bans (
  server_id uuid not null references public.servers(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  moderator_id uuid references public.profiles(id) on delete set null,
  reason text check (reason is null or char_length(reason) <= 500),
  created_at timestamptz not null default now(),
  primary key (server_id, user_id)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  server_id uuid not null references public.servers(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  target_user_id uuid references public.profiles(id) on delete set null,
  action text not null,
  target_type text,
  target_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_server_created_idx on public.audit_logs(server_id, created_at desc);

create table if not exists public.voice_commands (
  id uuid primary key default gen_random_uuid(),
  server_id uuid not null references public.servers(id) on delete cascade,
  target_user_id uuid not null references public.profiles(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null check (action in ('disconnect', 'move')),
  channel_id uuid references public.channels(id) on delete cascade,
  created_at timestamptz not null default now(),
  check ((action = 'disconnect' and channel_id is null) or (action = 'move' and channel_id is not null))
);
create index if not exists voice_commands_target_idx on public.voice_commands(target_user_id, created_at desc);

