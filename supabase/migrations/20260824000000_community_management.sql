create or replace function public.has_server_permission(
  target_server uuid,
  requested_permission text,
  target_user uuid default auth.uid()
) returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1
    from public.server_members member
    where member.server_id = target_server
      and member.user_id = target_user
      and (
        member.role in ('owner', 'admin')
        or exists (
          select 1
          from public.member_roles membership
          join public.server_roles role on role.id = membership.role_id and role.server_id = membership.server_id
          where membership.server_id = member.server_id
            and membership.user_id = member.user_id
            and (
              coalesce((role.permissions->>'administrator')::boolean, false)
              or coalesce((role.permissions->>requested_permission)::boolean, false)
            )
        )
      )
  );
$$;

create or replace function public.can_manage_server(target_server uuid, target_user uuid default auth.uid()) returns boolean
language sql stable security definer set search_path = public
as $$ select public.has_server_permission(target_server, 'manage_server', target_user); $$;

create or replace function public.member_hierarchy(target_server uuid, target_user uuid) returns integer
language sql stable security definer set search_path = public
as $$
  select case member.role
    when 'owner' then 2147483647
    when 'admin' then 1000000000
    else coalesce((
      select max(role.position)
      from public.member_roles membership
      join public.server_roles role on role.id = membership.role_id and role.server_id = membership.server_id
      where membership.server_id = target_server and membership.user_id = target_user
    ), 0)
  end
  from public.server_members member
  where member.server_id = target_server and member.user_id = target_user;
$$;

create or replace function public.can_act_on_member(target_server uuid, target_user uuid, actor uuid default auth.uid()) returns boolean
language sql stable security definer set search_path = public
as $$
  select actor <> target_user
    and coalesce(public.member_hierarchy(target_server, actor), -1) > coalesce(public.member_hierarchy(target_server, target_user), 2147483647);
$$;

create or replace function public.reply_belongs_to_channel(target_reply uuid, target_channel uuid) returns boolean
language sql stable security definer set search_path = public
as $$ select target_reply is null or exists(select 1 from public.messages where id = target_reply and channel_id = target_channel); $$;

create or replace function public.reply_belongs_to_direct(target_reply uuid, target_conversation uuid) returns boolean
language sql stable security definer set search_path = public
as $$ select target_reply is null or exists(select 1 from public.direct_messages where id = target_reply and conversation_id = target_conversation); $$;

