create or replace function public.create_server_role(
  target_server uuid,
  role_name text,
  role_color text,
  role_permissions jsonb default '{}'::jsonb
) returns uuid
language plpgsql security definer set search_path = public
as $$
declare new_role uuid; next_position integer;
begin
  if not public.has_server_permission(target_server, 'manage_roles') then raise exception 'Sem permissao para gerenciar cargos'; end if;
  select coalesce(max(position), 0) + 1 into next_position from public.server_roles where server_id = target_server;
  insert into public.server_roles(server_id, name, color, position, permissions)
  values (target_server, trim(role_name), lower(role_color), next_position, coalesce(role_permissions, '{}'::jsonb))
  returning id into new_role;
  perform public.write_audit(target_server, 'role.created', null, 'role', new_role::text, jsonb_build_object('name', trim(role_name)));
  return new_role;
end; $$;

create or replace function public.update_server_role(
  target_role uuid,
  role_name text,
  role_color text,
  role_position integer,
  role_permissions jsonb
) returns void
language plpgsql security definer set search_path = public
as $$
declare role_record public.server_roles%rowtype;
begin
  select * into role_record from public.server_roles where id = target_role;
  if role_record.id is null then raise exception 'Cargo nao encontrado'; end if;
  if role_record.is_everyone then
    if role_position <> 0 then raise exception 'O cargo @everyone deve permanecer na base'; end if;
  end if;
  if not public.has_server_permission(role_record.server_id, 'manage_roles') then raise exception 'Sem permissao para gerenciar cargos'; end if;
  if public.member_hierarchy(role_record.server_id, auth.uid()) <= greatest(role_record.position, role_position) then raise exception 'Cargo acima da sua hierarquia'; end if;
  update public.server_roles set
    name = case when is_everyone then '@everyone' else trim(role_name) end,
    color = lower(role_color),
    position = case when is_everyone then 0 else greatest(role_position, 1) end,
    permissions = coalesce(role_permissions, '{}'::jsonb)
  where id = target_role;
  perform public.write_audit(role_record.server_id, 'role.updated', null, 'role', target_role::text, jsonb_build_object('name', trim(role_name), 'position', role_position));
end; $$;

create or replace function public.delete_server_role(target_role uuid) returns void
language plpgsql security definer set search_path = public
as $$
declare role_record public.server_roles%rowtype;
begin
  select * into role_record from public.server_roles where id = target_role;
  if role_record.id is null then return; end if;
  if role_record.is_everyone then raise exception 'O cargo @everyone nao pode ser apagado'; end if;
  if not public.has_server_permission(role_record.server_id, 'manage_roles') then raise exception 'Sem permissao para gerenciar cargos'; end if;
  if public.member_hierarchy(role_record.server_id, auth.uid()) <= role_record.position then raise exception 'Cargo acima da sua hierarquia'; end if;
  delete from public.server_roles where id = target_role;
  perform public.write_audit(role_record.server_id, 'role.deleted', null, 'role', target_role::text, jsonb_build_object('name', role_record.name));
end; $$;

create or replace function public.assign_server_role(target_server uuid, target_user uuid, target_role uuid) returns void
language plpgsql security definer set search_path = public
as $$
declare selected_role public.server_roles%rowtype;
begin
  select * into selected_role from public.server_roles where id = target_role and server_id = target_server;
  if selected_role.id is null or selected_role.is_everyone then raise exception 'Cargo invalido'; end if;
  if not public.has_server_permission(target_server, 'manage_roles') then raise exception 'Sem permissao para gerenciar cargos'; end if;
  if not public.can_act_on_member(target_server, target_user) or public.member_hierarchy(target_server, auth.uid()) <= selected_role.position then raise exception 'Hierarquia insuficiente'; end if;
  insert into public.member_roles(server_id, user_id, role_id, assigned_by)
  values (target_server, target_user, target_role, auth.uid()) on conflict do nothing;
  perform public.write_audit(target_server, 'role.assigned', target_user, 'role', target_role::text, jsonb_build_object('name', selected_role.name));
end; $$;

create or replace function public.remove_server_role(target_server uuid, target_user uuid, target_role uuid) returns void
language plpgsql security definer set search_path = public
as $$
declare selected_role public.server_roles%rowtype;
begin
  select * into selected_role from public.server_roles where id = target_role and server_id = target_server;
  if selected_role.id is null then return; end if;
  if not public.has_server_permission(target_server, 'manage_roles') then raise exception 'Sem permissao para gerenciar cargos'; end if;
  if not public.can_act_on_member(target_server, target_user) or public.member_hierarchy(target_server, auth.uid()) <= selected_role.position then raise exception 'Hierarquia insuficiente'; end if;
  delete from public.member_roles where server_id = target_server and user_id = target_user and role_id = target_role;
  perform public.write_audit(target_server, 'role.removed', target_user, 'role', target_role::text, jsonb_build_object('name', selected_role.name));
end; $$;

create or replace function public.kick_server_member(target_server uuid, target_user uuid, reason text default null) returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.has_server_permission(target_server, 'kick_members') then raise exception 'Sem permissao para expulsar membros'; end if;
  if not public.can_act_on_member(target_server, target_user) then raise exception 'Hierarquia insuficiente'; end if;
  perform public.write_audit(target_server, 'member.kicked', target_user, 'member', target_user::text, jsonb_build_object('reason', nullif(trim(reason), '')));
  delete from public.server_members where server_id = target_server and user_id = target_user;
end; $$;

create or replace function public.ban_server_member(target_server uuid, target_user uuid, reason text default null) returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.has_server_permission(target_server, 'ban_members') then raise exception 'Sem permissao para banir membros'; end if;
  if not public.can_act_on_member(target_server, target_user) then raise exception 'Hierarquia insuficiente'; end if;
  insert into public.server_bans(server_id, user_id, moderator_id, reason)
  values (target_server, target_user, auth.uid(), nullif(trim(reason), ''))
  on conflict (server_id, user_id) do update set moderator_id = excluded.moderator_id, reason = excluded.reason, created_at = now();
  perform public.write_audit(target_server, 'member.banned', target_user, 'member', target_user::text, jsonb_build_object('reason', nullif(trim(reason), '')));
  delete from public.server_members where server_id = target_server and user_id = target_user;
end; $$;

create or replace function public.unban_server_member(target_server uuid, target_user uuid) returns void
language plpgsql security definer set search_path = public
as $$
begin
  if not public.has_server_permission(target_server, 'ban_members') then raise exception 'Sem permissao para remover banimento'; end if;
  delete from public.server_bans where server_id = target_server and user_id = target_user;
  perform public.write_audit(target_server, 'member.unbanned', target_user, 'member', target_user::text);
end; $$;

create or replace function public.issue_voice_command(
  target_server uuid,
  target_user uuid,
  command_action text,
  target_channel uuid default null
) returns uuid
language plpgsql security definer set search_path = public
as $$
declare command_id uuid;
begin
  if command_action not in ('disconnect', 'move') then raise exception 'Comando de voz invalido'; end if;
  if command_action = 'disconnect' and not public.has_server_permission(target_server, 'disconnect_members') then raise exception 'Sem permissao para desconectar membros'; end if;
  if command_action = 'move' and not public.has_server_permission(target_server, 'move_members') then raise exception 'Sem permissao para mover membros'; end if;
  if not public.can_act_on_member(target_server, target_user) then raise exception 'Hierarquia insuficiente'; end if;
  if command_action = 'move' and not exists(select 1 from public.channels where id = target_channel and server_id = target_server and kind = 'voice') then raise exception 'Canal de voz invalido'; end if;
  insert into public.voice_commands(server_id, target_user_id, actor_id, action, channel_id)
  values (target_server, target_user, auth.uid(), command_action, case when command_action = 'move' then target_channel else null end)
  returning id into command_id;
  perform public.write_audit(target_server, 'voice.' || command_action, target_user, 'voice', coalesce(target_channel::text, target_user::text));
  return command_id;
end; $$;

create or replace function public.join_server(invite_code text) returns uuid
language plpgsql security definer set search_path = public
as $$
declare target_server uuid; already_member boolean;
begin
  if auth.uid() is null then raise exception 'Nao autenticado'; end if;
  select server_id into target_server from public.invites
  where lower(code) = lower(trim(invite_code))
    and (expires_at is null or expires_at > now())
    and (max_uses is null or uses < max_uses)
  for update;
  if target_server is null then raise exception 'Convite invalido ou expirado'; end if;
  if exists(select 1 from public.server_bans where server_id = target_server and user_id = auth.uid()) then raise exception 'Voce esta banido deste servidor'; end if;
  select public.is_server_member(target_server) into already_member;
  insert into public.server_members(server_id, user_id) values (target_server, auth.uid()) on conflict do nothing;
  if not already_member then
    update public.invites set uses = uses + 1 where lower(code) = lower(trim(invite_code));
    perform public.write_audit(target_server, 'member.joined', auth.uid(), 'member', auth.uid()::text);
  end if;
  return target_server;
end; $$;

create or replace function public.audit_server_resource_change() returns trigger
language plpgsql security definer set search_path = public
as $$
declare target_server uuid; action_name text; resource_id text; details jsonb;
begin
  if tg_table_name = 'channels' then
    target_server := coalesce(new.server_id, old.server_id);
    resource_id := coalesce(new.id, old.id)::text;
    details := jsonb_build_object('name', coalesce(new.name, old.name), 'kind', coalesce(new.kind, old.kind));
  elsif tg_table_name = 'invites' then
    target_server := coalesce(new.server_id, old.server_id);
    resource_id := coalesce(new.code, old.code);
    details := '{}'::jsonb;
  else
    target_server := coalesce(new.id, old.id);
    resource_id := target_server::text;
    details := jsonb_build_object('name', coalesce(new.name, old.name));
  end if;
  action_name := rtrim(tg_table_name, 's') || '.' || lower(tg_op);
  perform public.write_audit(target_server, action_name, null, tg_table_name, resource_id, details);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end; $$;

